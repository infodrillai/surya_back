def determine_uom(name):
    upper = name.upper()
    if " MTR" in upper or "MTRS" in upper or "MTR " in upper:
        return "MTR"
    if "SET" in upper and ("BRACKET SET" in upper or "SET " in upper or " SET" in upper):
        return "SET"
    return "QTY"

def parse_items():
    lines = RAW_DATA.strip().split('\n')[1:]
    raw_items = []
    for line in lines:
        parts = line.split('\t')
        code = parts[0].strip() if len(parts) > 0 else ""
        name = parts[1].strip() if len(parts) > 1 else ""
        raw_items.append((code, name))

    processed = []
    for code, name in raw_items:
        # 1. Skip section headers
        if not code:
            if name in ("WINDER", "SQURE NUT / SPECIAL NUT"):
                continue
            if name == "LOCTITE 638":
                code = "SEO-LOC638"
            else:
                continue

        # 2. Split multi-codes like 'SEP031 / SEP032'
        if " / " in code:
            subcodes = [c.strip() for c in code.split('/')]
            for sc in subcodes:
                processed.append((sc, name, determine_uom(name)))
            continue
        
        if code == "051 TO 070":
            code = "SEW051-070"

        # Disambiguations
        if code == "SEP015" and "COMPLETE" in name.upper():
            code = "SEP015C"
        elif code == "SEBH251" and "W/O" in name.upper():
            code = "SEBH251-WO"
        elif code == "SEUB672" and "3S" in name.upper():
            code = "SEUB672-3S"
        elif code == "SEBR2063":
            if "FLT" in name.upper():
                code = "SEBR2063-FLT"
            elif "FAG" in name.upper():
                code = "SEBR2063-FAG"
        elif code == "SEO3101":
            if "DIAMOND" in name.upper():
                code = "SEO3101-D"
        elif code == "SEO3102":
            if "DIAMOND" in name.upper():
                code = "SEO3102-D"
        elif code == "SEW011":
            if "20MM OD" in name.upper():
                code = "SEW011-20OD"
        elif code == "SEW026":
            if "CIRCLIP" in name.upper():
                code = "SEW026-CC"
        elif code == "SEGS1311":
            if "STAR" in name.upper():
                code = "SEGS1311-STAR"
        elif code == "SEF865":
            if "FRAME" in name.upper() or "BOTTOM" in name.upper():
                code = "SEF865-B"
        elif code == "SEF866":
            if "NOVA" in name.upper():
                code = "SEF866-NOVA"
        elif code == "SEA198":
            if "CHONCHOID" in name.upper():
                code = "SEA198-AP"
        
        uom = determine_uom(name)
        processed.append((code, name, uom))

    final_list = []
    seen = {}
    for code, name, uom in processed:
        if code in seen:
            existing_name, _ = seen[code]
            if existing_name == name:
                continue
            else:
                m = re.search(r'(\d+X\d+X\d+|\d+x\d+x\d+)', name)
                suffix = m.group(1).upper() if m else "2"
                new_code = f"{code}-{suffix}"
                code = new_code
                while code in seen:
                    code = f"{code}-ALT"
        seen[code] = (name, uom)
        final_list.append((code, name, uom))

    return final_list

def run():
    items = parse_items()
    print(f"Total parsed items: {len(items)}")

    # Ensure UOMs
    for uom in ["QTY", "MTR", "SET"]:
        if not frappe.db.exists("UOM", uom):
            frappe.get_doc({"doctype": "UOM", "uom_name": uom}).insert(ignore_permissions=True)
            print(f"Created UOM: {uom}")

    inserted = 0
    updated = 0

    for code, name, uom in items:
        if frappe.db.exists("Product", code):
            doc = frappe.get_doc("Product", code)
            doc.product_name = name
            doc.product_type = "Finished"
            doc.total_steps = 3
            doc.uom = uom
            doc.save(ignore_permissions=True)
            updated += 1
        else:
            doc = frappe.get_doc({
                "doctype": "Product",
                "product_code": code,
                "product_name": name,
                "product_type": "Finished",
                "total_steps": 3,
                "uom": uom,
                "allow_negative_stock": 0,
                "is_scrap": 0
            })
            doc.insert(ignore_permissions=True)
            inserted += 1

    frappe.db.commit()
    print(f"Population complete! Inserted: {inserted}, Updated: {updated}")

    # Bump Master Version
    dummy_product = frappe.get_doc("Product", items[0][0])
    bump(dummy_product)
    frappe.db.commit()
    print(f"Master Version bumped successfully! Total products in DB: {frappe.db.count('Product')}")

