@frappe.whitelist()
def download_pdf(name):
    """Generates PDF for Quotation and returns base64 string + filename."""
    if not name:
        frappe.throw(_("Quotation name is required."))

    doc = frappe.get_doc("Quotation", name)
    # Check permissions
    if is_sales_person() and not is_admin():
        sp = get_current_sales_person()
        if sp and doc.sales_person and doc.sales_person != sp.name:
            frappe.throw(_("Unauthorized to view this Quotation."), frappe.PermissionError)

    html = _build_quotation_html(doc)
    try:
        pdf_bytes = get_pdf(html)
    except OSError:
        from weasyprint import HTML

        pdf_bytes = HTML(string=html).write_pdf()

    b64_content = base64.b64encode(pdf_bytes).decode("utf-8")

    # Record history
    try:
        frappe.get_doc({
            "doctype": "Comment",
            "comment_type": "Info",
            "reference_doctype": "Quotation",
            "reference_name": name,
            "content": f"PDF generated by {frappe.session.user}",
        }).insert(ignore_permissions=True)
    except Exception:
        pass

    return {
        "content": b64_content,
        "filename": f"{name}.pdf",
    }


@frappe.whitelist()
def email_pdf(name, recipient):
    """Emails quotation PDF to the specified recipient."""
    if not name or not recipient:
        frappe.throw(_("Quotation name and recipient email are required."))

    doc = frappe.get_doc("Quotation", name)
    html = _build_quotation_html(doc)
    try:
        pdf_bytes = get_pdf(html)
        attachments = [{"fname": f"{name}.pdf", "fcontent": pdf_bytes}]
    except Exception:
        attachments = []

    try:
        frappe.sendmail(
            recipients=[recipient],
        subject=f"Quotation {name} - CL Surya",
        message=f"<p>Dear Customer,</p><p>Please find attached Quotation <b>{name}</b>.</p><p>Total Amount: ₹{flt(doc.grand_total):,.2f}</p><p>Best regards,<br>CL Surya Team</p>",
        attachments=attachments,
        reference_doctype="Quotation",
        reference_name=name,
    )
    except frappe.OutgoingEmailError:
        frappe.throw(_("Please setup default outgoing Email Account from Tools > Email Account in Frappe Desk."))
    except Exception as e:
        frappe.throw(_("Email could not be sent: {0}. Please ensure outgoing Email Account is configured.").format(str(e)))

    try:
        frappe.get_doc({
            "doctype": "Comment",
            "comment_type": "Info",
            "reference_doctype": "Quotation",
            "reference_name": name,
            "content": f"Quotation emailed to {recipient} by {frappe.session.user}",
        }).insert(ignore_permissions=True)
    except Exception:
        pass

    return {"message": "Email sent successfully"}


@frappe.whitelist()
def pdf_history(name):
    """Returns generation history for Quotation."""
    if not name:
        return []

    # Get comments / files attached
    history = []
    files = frappe.get_all(
        "File",
        filters={"attached_to_doctype": "Quotation", "attached_to_name": name},
        fields=["file_name", "file_url", "creation", "file_size"],
        order_by="creation desc",
    )
    for f in files:
        history.append({
            "file_name": f.file_name,
            "file_url": f.file_url,
            "creation": format_date(f.creation, "dd-mm-yyyy HH:mm"),
            "size": f"{flt(f.file_size or 0) / 1024:.1f} KB",
        })

    # Also include info comments
    comments = frappe.get_all(
        "Comment",
        filters={"reference_doctype": "Quotation", "reference_name": name, "comment_type": "Info"},
        fields=["content", "owner", "creation"],
        order_by="creation desc",
    )
    for c in comments:
        history.append({
            "file_name": c.content,
            "file_url": "",
            "creation": format_date(c.creation, "dd-mm-yyyy HH:mm"),
            "size": c.owner,
        })

    if not history:
        history.append({
            "file_name": f"{name}.pdf (Auto-generated on download)",
            "file_url": "",
            "creation": nowdate(),
            "size": "—",
        })

    return history


@frappe.whitelist()
def activity(name):
    """Returns version audit log changes for the Quotation."""
    if not name:
        return []

    versions = frappe.get_all(
        "Version",
        filters={"ref_doctype": "Quotation", "docname": name},
        fields=["owner", "creation", "data"],
        order_by="creation desc",
        limit=50,
    )

    if not versions:
        # Fallback to doc creation & comments
        doc = frappe.get_doc("Quotation", name)
        return [
            {
                "owner": doc.owner,
                "creation": str(doc.creation)[:19],
                "data": json.dumps({"changed": [["Status", "", doc.status or "Draft"], ["Grand Total", "", f"₹{flt(doc.grand_total):,.2f}"]], "comment": "Quotation created"}),
            }
        ]

    return versions


@frappe.whitelist()
def performance():
    """Returns sales performance statistics for the logged-in user or sales person."""
    sp = get_current_sales_person()
    sp_filter = {}
    if sp and not is_admin():
        sp_filter["sales_person"] = sp.name

    quotes = frappe.get_all(
        "Quotation",
        filters=sp_filter,
        fields=["name", "grand_total", "status", "quotation_date", "customer"],
    )

    orders = frappe.get_all(
        "Sales Order",
        filters=sp_filter,
        fields=["name", "grand_total", "status", "order_date", "quotation"],
    )

    total_quotes = len(quotes)
    accepted_quotes = sum(1 for q in quotes if q.get("status") in ("Accepted", "Approved"))
    total_quoted_val = sum(flt(q.get("grand_total") or 0) for q in quotes)
    total_ordered_val = sum(flt(o.get("grand_total") or 0) for o in orders)
    win_rate = (accepted_quotes / total_quotes * 100) if total_quotes > 0 else 0

    return [
        {"metric": "Total Quotations", "value": str(total_quotes), "notes": "Total quotations prepared"},
        {"metric": "Accepted / Approved", "value": str(accepted_quotes), "notes": f"Win rate: {win_rate:.1f}%"},
        {"metric": "Total Quoted Value", "value": f"₹{total_quoted_val:,.2f}", "notes": "Gross quote amount"},
        {"metric": "Total Sales Orders", "value": str(len(orders)), "notes": "Orders converted"},
        {"metric": "Total Order Value", "value": f"₹{total_ordered_val:,.2f}", "notes": "Confirmed revenue"},
    ]


@frappe.whitelist()
def product_references(product):
    """Returns price history and production history for a product."""
    if not product:
        return {"monthly_prices": [], "production_history": []}

    # Quotation and order line rates
    q_items = frappe.db.sql("""
        SELECT qi.rate, q.quotation_date, qi.uom
        FROM `tabQuotation Item` qi
        JOIN `tabQuotation` q ON q.name = qi.parent
        WHERE qi.product = %(product)s
        ORDER BY q.quotation_date DESC
        LIMIT 50
    """, {"product": product}, as_dict=True)

    monthly_dict = {}
    for r in q_items:
        m = str(r.quotation_date)[:7] if r.quotation_date else "Recent"
        if m not in monthly_dict:
            monthly_dict[m] = {"rates": [], "uom": r.uom or "PCS"}
        monthly_dict[m]["rates"].append(flt(r.rate))

    monthly_prices = []
    for m, d in sorted(monthly_dict.items(), reverse=True):
        avg = sum(d["rates"]) / len(d["rates"]) if d["rates"] else 0
        monthly_prices.append({
            "month": m,
            "uom": d["uom"],
            "average": f"₹{avg:,.2f}",
        })

    if not monthly_prices:
        monthly_prices.append({
            "month": "Current",
            "uom": frappe.db.get_value("Product", product, "uom") or "PCS",
            "average": "No prior quotes",
        })

    # Production history
    prod_hist = []
    for dt, stage_name in [("Stage 3 Batch", "PU Stage 3"), ("Belt Batch", "Belt Batch")]:
        if frappe.db.exists("DocType", dt):
            try:
                batches = frappe.get_all(
                    dt,
                    filters={"product": product},
                    fields=["name", "quantity", "unit_cost", "modified", "is_completed"],
                    order_by="modified desc",
                    limit=10,
                )
                for b in batches:
                    prod_hist.append({
                        "month": f"Batch {b.name} ({stage_name})",
                        "unit": f"{flt(b.quantity):,.0f} qty",
                        "average_selling_price": f"Cost: ₹{flt(b.unit_cost):,.2f}",
                    })
            except Exception:
                pass

    return {
        "monthly_prices": monthly_prices,
        "production_history": prod_hist,
    }


def _build_quotation_html(doc):
    """Generates standard HTML layout for quotation PDF."""
    company_name = frappe.conf.get("company_name") or "CLS Surya"
    
    items = doc.items or []
    discounted_items = [i for i in items if flt(getattr(i, 'item_discount_percent', 0)) > 0]
    discounted_count = len(discounted_items)
    show_discount_col = discounted_count > 1

    items_rows = ""
    for idx, item in enumerate(items, 1):
        # Resolve product image and embed it as a data URI for PDF generation
        product_image = getattr(item, 'image', '') or ''
        if not product_image and item.product:
            try:
                product_image = frappe.db.get_value("Product", item.product, "image") or ""
            except Exception:
                product_image = ""
        # If the image reference is not a full URL, turn it into a base64 data URI so the PDF renderer can embed it
        if product_image and not (product_image.startswith('http://') or product_image.startswith('https://')):
            try:
                import os, mimetypes
                # Try to fetch the File doc first
                if frappe.db.exists('File', product_image):
                    file_doc = frappe.get_doc('File', product_image)
                    file_path = file_doc.file_path if hasattr(file_doc, 'file_path') else None
                else:
                    # Assume it's a /files/... path relative to public folder
                    if product_image.startswith('/files/'):
                        from frappe.utils import get_site_path
                        file_path = get_site_path('public', product_image.lstrip('/'))
                    else:
                        file_path = None
                if file_path and os.path.exists(file_path):
                    with open(file_path, 'rb') as f:
                        encoded = base64.b64encode(f.read()).decode()
                    mime = mimetypes.guess_type(file_path)[0] or 'image/png'
                    product_image = f"data:{mime};base64,{encoded}"
                else:
                    product_image = ''
            except Exception:
                product_image = ''

        item_disc_pct = flt(getattr(item, 'item_discount_percent', 0))
        gross_amt = flt(getattr(item, 'gross_amount', 0)) or (flt(item.quantity) * flt(item.rate))
        item_disc_amt = flt(getattr(item, 'item_discount_amount', 0)) or (gross_amt * item_disc_pct / 100.0)
        net_amt = flt(getattr(item, 'amount', 0)) or (gross_amt - item_disc_amt)

        image_html = f"""<div style="width: 38px; height: 38px; min-width: 38px; border: 1px solid #ddd; border-radius: 4px; display: inline-flex; align-items: center; justify-content: center; overflow: hidden; background: #fafafa; margin-right: 8px; vertical-align: top;"><img src="{product_image}" style="width: 100%; height: 100%; object-fit: contain;" /></div>""" if product_image else """<div style="width: 38px; height: 38px; min-width: 38px; border: 1px solid #ddd; border-radius: 4px; display: inline-flex; align-items: center; justify-content: center; overflow: hidden; background: #fafafa; margin-right: 8px; vertical-align: top; font-size: 8px; color: #999;">—</div>"""

        single_disc_html = ""

        disc_td = f"""<td style="padding: 6px; border: 1px solid #ddd; text-align: right; color: #16a34a; font-weight: 600;">{f"{item_disc_pct:.1f}%" if item_disc_pct > 0 else "—"}</td>""" if show_discount_col else ""

        items_rows += f"""
        <tr>
            <td style="padding: 6px; border: 1px solid #ddd; text-align: center;">{idx}</td>
            <td style="padding: 6px; border: 1px solid #ddd;">
                <table style="border-collapse: collapse; width: 100%; border: none;">
                    <tr>
                        <td style="width: 46px; border: none; padding: 0; vertical-align: top;">{image_html}</td>
                        <td style="border: none; padding: 0; vertical-align: top;">
                            <b>{item.product}</b>
                            {getattr(item, 'description', '') and f"<div style='font-size: 10px; color: #666;'>{item.description}</div>" or ""}
                            {single_disc_html}
                        </td>
                    </tr>
                </table>
            </td>
            <td style="padding: 6px; border: 1px solid #ddd; text-align: center;">{item.uom or 'PCS'}</td>
            <td style="padding: 6px; border: 1px solid #ddd; text-align: right;">{flt(item.quantity):,.2f}</td>
            <td style="padding: 6px; border: 1px solid #ddd; text-align: right;">₹{flt(item.rate):,.2f}</td>
            {disc_td}
            <td style="padding: 6px; border: 1px solid #ddd; text-align: right; font-weight: bold;">₹{net_amt:,.2f}</td>
        </tr>
        """

    disc_th = """<th style="width: 10%; text-align: right;">Discount</th>""" if show_discount_col else ""

    single_disc_item = discounted_items[0] if discounted_count == 1 else None
    single_item_disc_row = ""
    if single_disc_item:
        s_name = getattr(single_disc_item, 'product', '')
        s_pct = flt(getattr(single_disc_item, 'item_discount_percent', 0))
        s_gross = flt(getattr(single_disc_item, 'gross_amount', 0)) or (flt(single_disc_item.quantity) * flt(single_disc_item.rate))
        s_amt = flt(getattr(single_disc_item, 'item_discount_amount', 0)) or (s_gross * s_pct / 100.0)
        if s_amt > 0:
            single_item_disc_row = f"<tr><td>Product Discount ({s_pct:.1f}% on {s_name}):</td><td style='text-align: right; color: #16a34a;'>-₹{s_amt:,.2f}</td></tr>"

    html = f"""
    <!DOCTYPE html>
    <html>
    <head>
        <meta charset="utf-8">
        <title>Quotation {doc.name}</title>
        <style>
            body {{ font-family: 'Helvetica Neue', Helvetica, Arial, sans-serif; font-size: 13px; color: #333; margin: 20px; }}
            .header {{ border-bottom: 2px solid #0f766e; padding-bottom: 12px; margin-bottom: 20px; }}
            .company {{ font-size: 22px; font-weight: bold; color: #0f766e; }}
            .quote-title {{ font-size: 18px; font-weight: bold; float: right; color: #1e293b; }}
            .meta-table {{ width: 100%; margin-bottom: 20px; }}
            .items-table {{ width: 100%; border-collapse: collapse; margin-bottom: 20px; }}
            .items-table th {{ background: #f1f5f9; padding: 8px; border: 1px solid #ddd; font-weight: bold; text-align: left; }}
            .totals-table {{ width: 48%; float: right; border-collapse: collapse; margin-top: 10px; }}
            .totals-table td {{ padding: 6px 10px; border: 1px solid #ddd; }}
        </style>
    </head>
    <body>
        <div class="header">
            <span class="quote-title">QUOTATION: {doc.name}</span>
            <div class="company">{company_name}</div>
            <div>Date: {doc.quotation_date or nowdate()} | Status: {doc.status or 'Draft'}</div>
        </div>
        <table class="meta-table">
            <tr>
                <td style="width: 50%; vertical-align: top;">
                    <strong>Customer:</strong> {doc.customer}<br>
                    {f"<strong>Sales Person:</strong> {doc.sales_person}<br>" if getattr(doc, 'sales_person', None) else ""}
                </td>
                <td style="width: 50%; vertical-align: top; text-align: right;">
                    <strong>Valid Until:</strong> {getattr(doc, 'valid_until', '—') or '—'}<br>
                    <strong>Version:</strong> v{getattr(doc, 'version', 1) or 1}
                </td>
            </tr>
        </table>
        <table class="items-table">
            <thead>
                <tr>
                    <th style="width: 5%; text-align: center;">#</th>
                    <th>Item / Product</th>
                    <th style="width: 8%; text-align: center;">UOM</th>
                    <th style="width: 10%; text-align: right;">Qty</th>
                    <th style="width: 12%; text-align: right;">Rate</th>
                    {disc_th}
                    <th style="width: 14%; text-align: right;">Amount</th>
                </tr>
            </thead>
            <tbody>
                {items_rows}
            </tbody>
        </table>
        <table class="totals-table">
            <tr><td>Item Subtotal:</td><td style="text-align: right;">₹{flt(doc.subtotal):,.2f}</td></tr>
            {single_item_disc_row}
            <tr><td>Overall Quotation Discount ({flt(doc.discount_percent):.1f}%):</td><td style="text-align: right;">-₹{flt(doc.discount_amount):,.2f}</td></tr>
            {f"<tr><td>Packing Charges:</td><td style='text-align: right;'>₹{flt(getattr(doc, 'packing_charges', 0)):,.2f}</td></tr>" if flt(getattr(doc, 'packing_charges', 0)) > 0 else ""}
            {f"<tr><td>Transport Charges:</td><td style='text-align: right;'>₹{flt(getattr(doc, 'transport_charges', 0)):,.2f}</td></tr>" if flt(getattr(doc, 'transport_charges', 0)) > 0 else ""}
            <tr><td>GST Amount:</td><td style="text-align: right;">₹{flt(doc.tax_amount):,.2f}</td></tr>
            <tr style="font-weight: bold; background: #f8fafc;"><td>Grand Total:</td><td style="text-align: right; color: #0f766e; font-size: 14px;">₹{flt(doc.grand_total):,.2f}</td></tr>
        </table>
    </body>
    </html>
    """
    return html
